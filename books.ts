// 자주 쓰는 다른 이름들
const ALIASES: Record<string, number> = {
  '로마': 45, '계시록': 65, '애가': 24, '시': 18, '아가서': 21,
  '롯기': 7, '욥': 17, '마태': 39, '마가': 40, '누가': 41, '행전': 44,
};

/** 책 이름/약어 문자열 → 책 index (못 찾으면 -1) */
export function findBook(raw: string): number {
  const s = raw.replace(/\s+/g, '');
  if (!s) return -1;
  let i = BOOKS.findIndex(b => b.abbr === s);
  if (i >= 0) return i;
  i = BOOKS.findIndex(b => b.name === s);
  if (i >= 0) return i;
  if (s in ALIASES) return ALIASES[s];
  // 숫자 접두사: 1요 → 요일, 2고 → 고후 등
  const m = s.match(/^([123])(.+)$/);
  if (m) {
    const n = m[1], rest = m[2];
    const map: Record<string, string[]> = {
      '요': ['요일', '요이', '요삼'], '요한': ['요일', '요이', '요삼'],
      '고': ['고전', '고후'], '고린도': ['고전', '고후'],
      '살': ['살전', '살후'], '데살로니가': ['살전', '살후'],
      '딤': ['딤전', '딤후'], '디모데': ['딤전', '딤후'],
      '벧': ['벧전', '벧후'], '베드로': ['벧전', '벧후'],
      '삼': ['삼상', '삼하'], '사무엘': ['삼상', '삼하'],
      '왕': ['왕상', '왕하'], '열왕기': ['왕상', '왕하'],
      '대': ['대상', '대하'], '역대': ['대상', '대하'],
    };
    const arr = map[rest];
    if (arr && arr[+n - 1]) return BOOKS.findIndex(b => b.abbr === arr[+n - 1]);
  }
  // 앞부분이 일치하는 책 (예: "고린도" → 고린도전서)
  i = BOOKS.findIndex(b => b.name.startsWith(s));
  return i;
}
