export interface Span { book: number; c1: number; v1: number; c2: number; v2: number }
export interface Topic { name: string; alias: string[]; spans: Span[]; also: Span[] }

function parseSpan(s: string): Span | null {
  const m = s.trim().match(/^([123]?\s*[가-힣]+)\s*(\d+)(?::(\d+))?(?:-(\d+)(?::(\d+))?)?$/);
  if (!m) return null;
  const book = findBook(m[1]);
  if (book < 0) return null;
  const c1 = +m[2];
  if (!m[3]) { // 장 전체 (마 5-7 같은 장 범위도)
    const c2 = m[4] ? +m[4] : c1;
    return { book, c1, v1: 1, c2, v2: 999 };
  }
  const v1 = +m[3];
  if (m[5]) return { book, c1, v1, c2: +m[4], v2: +m[5] };
  return { book, c1, v1, c2: c1, v2: m[4] ? +m[4] : v1 };
}

let TOPICS: Topic[] | null = null;
export function allTopics(): Topic[] {
  if (TOPICS) return TOPICS;
  TOPICS = RAW.trim().split('\n').map(line => {
    const [name, alias = '', refs = '', also = ''] = line.split('|');
    return {
      name: name.trim(),
      alias: alias.split(',').map(a => a.trim()).filter(Boolean),
      spans: refs.split(';').map(parseSpan).filter((x): x is Span => !!x),
      also: also.split(';').map(parseSpan).filter((x): x is Span => !!x),
    };
  }).filter(t => t.name && t.spans.length);
  return TOPICS;
}

/** "마 5:3-12", "창 6:9-8:22" */
export function spanLabel(s: Span, data?: BibleData): string {
  const b = BOOKS[s.book].abbr;
  const lastV = (c: number) => data?.[s.book]?.[c - 1]?.length ?? 999;
  if (s.v1 === 1 && s.v2 >= lastV(s.c2)) return s.c1 === s.c2 ? `${b} ${s.c1}${s.book === 18 ? '편' : '장'}` : `${b} ${s.c1}-${s.c2}장`;
  if (s.c1 === s.c2) return s.v1 === s.v2 ? `${b} ${s.c1}:${s.v1}` : `${b} ${s.c1}:${s.v1}-${s.v2}`;
  return `${b} ${s.c1}:${s.v1}-${s.c2}:${s.v2}`;
}

/** 범위 안의 절들 */
export function spanVerses(data: BibleData, s: Span): { c: number; v: number; t: string }[] {
  const out: { c: number; v: number; t: string }[] = [];
  for (let c = s.c1; c <= s.c2; c++) {
    const ch = data[s.book]?.[c - 1];
    if (!ch) break;
    const from = c === s.c1 ? s.v1 : 1;
    const to = c === s.c2 ? Math.min(s.v2, ch.length) : ch.length;
    for (let v = from; v <= to; v++) out.push({ c, v, t: ch[v - 1] });
  }
  return out;
}

/* ---------- 찾기: 정확히 → 포함 → 낱말 모두 → 자모가 비슷 (음성 입력 오타) ---------- */
const norm = (s: string) => s.replace(/\([^)]*\)/g, '').replace(/[^가-힣a-z0-9]/gi, '').toLowerCase();
// 말끝에 붙는 "에 대해", "이야기" 같은 말은 떼고 비교
const TAIL = /(에대해서?|에대한|이야기|사건|말씀|구절|본문|성경|비유|이란|란|은|는|이|가|을|를)$/;

const CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ';
const JUNG = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ';
const JONG = ' ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ';
function jamo(s: string): string {
  let out = '';
  for (const ch of s) {
    const c = ch.charCodeAt(0) - 0xac00;
    if (c < 0 || c > 11171) { out += ch; continue; }
    out += CHO[Math.floor(c / 588)] + JUNG[Math.floor((c % 588) / 28)] + (c % 28 ? JONG[c % 28] : '');
  }
  return out;
}
function edit(a: string, b: string, cap: number): number {
  if (Math.abs(a.length - b.length) > cap) return cap + 1;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    let best = i;
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      if (cur[j] < best) best = cur[j];
    }
    if (best > cap) return cap + 1;
    prev = cur;
  }
  return prev[b.length];
}

export interface TopicHit { topic: Topic; score: number; via?: string }

export function findTopics(query: string, max = 3): TopicHit[] {
  let q = norm(query);
  if (q.length < 2) return [];
  const q2 = q.replace(TAIL, '');
  if (q2.length >= 2) q = q2;
  const words = query.split(/\s+/).map(w => norm(w).replace(TAIL, '')).filter(w => w.length >= 2);
  const qj = jamo(q);
  const hits: TopicHit[] = [];
  for (const t of allTopics()) {
    let best = 0, via: string | undefined;
    for (const name of [t.name, ...t.alias]) {
      const n = norm(name);
      if (!n) continue;
      let sc = 0;
      if (n === q) sc = 100;
      else if (n.length >= 2 && q.includes(n) && n.length >= q.length * 0.5) sc = 80;   // "팔복에 대해" ⊃ "팔복"
      else if (q.length >= 2 && n.includes(q) && q.length >= n.length * 0.5) sc = 70; // "탕자" ⊂ "탕자 비유"
      else if (words.length >= 2 && words.every(w => n.includes(w))) sc = 65;           // "다윗 골리앗"
      else {
        // 음성 입력 오타: 자모 단위로 거의 같으면 (팔목 → 팔복, 주기도믄 → 주기도문)
        const nj = jamo(n);
        const cap = nj.length <= 6 ? 1 : nj.length <= 12 ? 2 : 3;
        const d = edit(qj, nj, cap);
        if (d <= cap) sc = 60 - d * 5;
      }
      if (sc > best) { best = sc; via = name === t.name ? undefined : name; }
    }
    if (best) hits.push({ topic: t, score: best, via });
  }
  hits.sort((a, b) => b.score - a.score);
  // 정확히 맞는 것이 있으면 그것만 (비슷한 것들은 아래로)
  const top = hits[0]?.score ?? 0;
  return hits.filter(h => h.score >= Math.min(top, 80) || h.score >= top - 10).slice(0, max);
}
